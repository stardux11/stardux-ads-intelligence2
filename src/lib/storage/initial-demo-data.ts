// Gerador de anúncios de demonstração consistentes
function createDemoAd(params: {
  id: string;
  advertiser_id: string;
  advertiser_name: string;
  project_id?: string;
  niche_id: string;
  niche_name: string;
  external_id: string;
  started_days_ago: number;
  format: 'image' | 'video' | 'carousel';
  headline: string;
  body_text: string;
  description: string;
  cta_text: string;
  media_url: string;
  destination_url: string;
  variation_count?: number;
}): Ad {
  const now = new Date('2026-10-20T14:00:00Z');
  const startedAt = new Date(now.getTime() - params.started_days_ago * 24 * 60 * 60 * 1000);

  const isc = calculateISC({
    daysActive: params.started_days_ago,
    variationCount: params.variation_count || 2,
    advertiserActiveAdsCount: 3,
    format: params.format,
    platforms: ['facebook', 'instagram'],
    source: 'meta_ad_library',
    originalUrl: `https://www.facebook.com/ads/library/?id=${params.external_id}`,
  });

  return {
    id: params.id,
    organization_id: 'org-default',
    advertiser_id: params.advertiser_id,
    advertiser_name: params.advertiser_name,
    project_id: params.project_id,
    niche_id: params.niche_id,
    niche_name: params.niche_name,
    external_id: params.external_id,
    original_url: `https://www.facebook.com/ads/library/?id=${params.external_id}`,
    source: 'meta_ad_library',
    country: 'BR',
    platforms: ['facebook', 'instagram'],
    format: params.format,
    status_observed: 'active',
    started_at: startedAt.toISOString(),
    last_verified_at: '2026-10-19T10:00:00Z',
    days_active_observed: params.started_days_ago,
    headline: params.headline,
    body_text: params.body_text,
    description: params.description,
    cta_text: params.cta_text,
    destination_url: params.destination_url,
    media_url: params.media_url,
    thumbnail_url: params.media_url,
    isc_score: isc.totalScore,
    isc_breakdown: isc,
    is_demo: true,
    data_confidence: 'verified_source',
    created_at: startedAt.toISOString(),
    updated_at: '2026-10-19T10:00:00Z',
  };
}

